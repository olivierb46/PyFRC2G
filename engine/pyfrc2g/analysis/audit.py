"""
Risk detection on firewall rules (works on the normalized CSV rows).

Checks:
    ANY_ANY            pass rule from any source to any destination
    WAN_EXPOSED        pass rule on an Internet-facing interface opening admin/sensitive ports
    (automatic rules generated by the firewall, column AUTOMATIC, get no finding of their own,
    but still shadow the rules that follow them)
    SHADOWED           rule never reached: an earlier rule on the same interface matches first
    REDUNDANT          rule fully covered by an earlier rule with the same action
    PARTIAL_OVERLAP    part of the traffic of a rule is decided earlier by a rule with another action

Aliases, interface networks ("LAN net"), firewall addresses and port aliases are expanded
(see netmodel) so that e.g. a rule on 10.0.1.0/24 is seen as shadowed by an earlier rule on an
alias containing 10.0.0.0/16.

Other modules add findings to the same list: UNUSED / NO_RECENT_TRAFFIC (analysis.hits)
and POLICY:<id> (analysis.policy).
    DISABLED           disabled rule still present in the configuration
    NO_DESCRIPTION     rule without description
"""

from pyfrc2g import utils
from pyfrc2g.model import netmodel
from pyfrc2g.model.rules import interface_names, is_true, rule_summary

AUDIT_FIELDNAMES = ["SEVERITY", "CHECK", "GATEWAY", "RULE ORDER", "RULE ID", "RULE", "DETAIL"]
SEVERITIES = ["CRITICAL", "HIGH", "MEDIUM", "LOW"]

_FIREWALL_SELF_MARKERS = ("address", "(self)", "this firewall", "this_firewall")


def _ports_intersect(ranges, ports):
    """Return sorted ports of `ports` included in ranges (None = any port)."""
    if ranges is None:
        return sorted(ports)
    return sorted(p for p in ports if any(lo <= p <= hi for lo, hi in ranges))


def _wan_names(config):
    names = {n.lower() for n in getattr(config, "wan_interfaces", ["wan"])}
    names |= netmodel.wan_interfaces()
    for iface in list(names):
        descr = utils.API_INTERFACE_MAP.get(iface)
        if descr:
            names.add(str(descr).lower())
    return names


def make_finding(severity, check, row, detail):
    """Audit finding dict (AUDIT_FIELDNAMES) for one rule row."""
    return {
        "SEVERITY": severity,
        "CHECK": check,
        "GATEWAY": row.get("GATEWAY", ""),
        "RULE ORDER": row.get("RULE ORDER", ""),
        "RULE ID": row.get("RULE ID", ""),
        "RULE": rule_summary(row),
        "DETAIL": detail,
    }


def _check_rule(row, config, wan_names):
    """Checks that only look at one rule."""
    findings = []
    if is_true(row.get("AUTOMATIC")):
        return findings  # Generated by the firewall, not configured by the administrator.
    action = (row.get("ACTION") or "").strip().lower()
    enabled = not is_true(row.get("DISABLED"))

    if not enabled:
        findings.append(make_finding("LOW", "DISABLED", row,
                                 "Disabled rule still present: remove it if it is no longer needed."))
    comment = (row.get("COMMENT") or "").strip()
    terminal = action in ("pass", "block", "reject")
    if terminal and (not comment or comment.lower() == "any"):
        findings.append(make_finding("LOW", "NO_DESCRIPTION", row,
                                 "Rule without description: purpose cannot be audited."))
    if not enabled or action != "pass" or row.get("_ESTABLISHED"):
        return findings

    rule = netmodel.compiled(row)
    src_any = rule.src.any and not rule.src.negated
    # Loopback and locally generated traffic (iptables/nft OUTPUT chain) are not exposures.
    local_only = rule.in_iface == "lo" or rule.group.rsplit("/", 1)[-1].lower() == "output"
    any_any = src_any and rule.dst.any and not rule.dst.negated and not local_only
    if any_any:
        if rule.ports.any and rule.protos is None:
            findings.append(make_finding("CRITICAL", "ANY_ANY", row,
                                     "Any source to any destination, any protocol and port."))
        else:
            scope = []
            if rule.protos is not None:
                scope.append("protocol " + "/".join(sorted(rule.protos)))
            if not rule.ports.any:
                scope.append(f"ports {row.get('PORT')}")
            findings.append(make_finding("MEDIUM", "ANY_ANY", row,
                                     f"Any source to any destination ({', '.join(scope)})."))

    is_floating = is_true(row.get("FLOATING"))
    on_wan = interface_names(row.get("GATEWAY", "")) & wan_names or (rule.in_iface in wan_names)
    if not is_floating and on_wan:
        if not src_any:
            return findings
        ranges = None if rule.ports.any else rule.ports.ranges
        if ranges == []:
            return findings  # Unresolved alias: cannot tell.
        destination = (row.get("DESTINATION") or "").lower()
        to_firewall = (any(marker in destination for marker in _FIREWALL_SELF_MARKERS)
                       or any(item.key == "self" or item.key.startswith("addr:")
                              for item in rule.dst.items))
        admin = _ports_intersect(ranges, config.admin_ports)
        sensitive = _ports_intersect(ranges, config.sensitive_ports)
        if ranges is None and not any_any:
            findings.append(make_finding("HIGH", "WAN_EXPOSED", row,
                                     "All ports open from the Internet."))
        elif admin and to_firewall:
            findings.append(make_finding("CRITICAL", "WAN_EXPOSED", row,
                                     f"Firewall administration exposed to the Internet "
                                     f"(ports {', '.join(map(str, admin))})."))
        elif admin or sensitive:
            ports = ", ".join(map(str, sorted(set(admin) | set(sensitive))))
            findings.append(make_finding("HIGH", "WAN_EXPOSED", row,
                                     f"Administration/sensitive ports open from the Internet "
                                     f"({ports})."))
    return findings


def _check_shadowing(rows):
    """
    First-match analysis per interface (floating rules are excluded: last-match by default).
    Reports, for each rule, the first earlier rule that fully covers it (SHADOWED / REDUNDANT)
    or, failing that, that overlaps it with another action (PARTIAL_OVERLAP).
    """
    findings = []
    by_gateway = {}
    for rule in netmodel.compile_rules(rows):
        if rule.floating or not rule.enabled or rule.established_only \
                or rule.action not in ("pass", "block", "reject"):
            continue  # iptables/nft log / jump / return rules do not end the evaluation.
        by_gateway.setdefault(rule.group, []).append(rule)

    for rules in by_gateway.values():
        rules.sort(key=lambda r: r.order)
        for index, rule in enumerate(rules):
            if rule.automatic:
                continue  # Automatic rules are only used as earlier rules (they do decide traffic).
            overlap = None
            for earlier in rules[:index]:
                if earlier.in_iface != rule.in_iface and earlier.in_iface:
                    continue  # iptables/nft: earlier rule limited to another input interface.
                if not earlier.quick:
                    continue  # pf non-quick rule: a later match overrides it.
                if "any" not in (earlier.direction, rule.direction) and earlier.direction != rule.direction:
                    continue  # Inbound and outbound rules filter different packets.
                if netmodel.rule_covers(earlier, rule):
                    if earlier.action == rule.action:
                        findings.append(make_finding(
                            "LOW", "REDUNDANT", rule.row,
                            f"Already covered by rule #{earlier.order} (same action)."))
                    else:
                        findings.append(make_finding(
                            "MEDIUM", "SHADOWED", rule.row,
                            f"Never reached: rule #{earlier.order} ({earlier.action}) "
                            f"matches the same traffic first."))
                    overlap = None
                    break
                if (overlap is None and earlier.action != rule.action and not earlier.automatic
                        and netmodel.rule_intersects(earlier, rule) is True
                        and not netmodel.rule_covers(rule, earlier)):
                    overlap = earlier
            else:
                if overlap is not None:
                    findings.append(make_finding(
                        "LOW", "PARTIAL_OVERLAP", rule.row,
                        f"Part of this traffic is decided first by rule #{overlap.order} "
                        f"({overlap.action}): {overlap.row.get('SOURCE')} -> "
                        f"{overlap.row.get('DESTINATION')} [{overlap.row.get('PORT')}]."))
    return findings


def audit_rules(rows, config):
    """
    Run all checks on normalized rule rows.

    Returns:
        list: Findings (dicts with AUDIT_FIELDNAMES keys), most severe first.
    """
    wan_names = _wan_names(config)
    findings = []
    for row in rows:
        findings.extend(_check_rule(row, config, wan_names))
    findings.extend(_check_shadowing(rows))
    return sort_findings(findings)


def sort_findings(findings):
    """Most severe first, then by gateway and rule order."""
    rank = {s: i for i, s in enumerate(SEVERITIES)}

    def sort_key(f):
        try:
            order = int(f["RULE ORDER"] or 0)
        except ValueError:
            order = 0
        return rank.get(f["SEVERITY"], 99), f["GATEWAY"], order

    return sorted(findings, key=sort_key)


def count_by_severity(findings):
    counts = dict.fromkeys(SEVERITIES, 0)
    for f in findings:
        counts[f["SEVERITY"]] = counts.get(f["SEVERITY"], 0) + 1
    return counts
