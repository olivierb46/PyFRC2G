"""
Normalized rule rows: conversion of parsed / API rule entries into the rows used by every
report (CSV columns + private "_" keys with raw values for the analysis modules), filters, and
small helpers shared by the audit, diff, hits and report modules.

Row keys:
    CSV columns (config.CSV_FIELDNAMES): SOURCE, GATEWAY, ACTION, PROTOCOL, PORT, DESTINATION,
        COMMENT, DISABLED, FLOATING, RULE ORDER, RULE ID, IP VERSION
    Private keys (never written): _SRC/_DST/_PORT/_PROTO raw values, _IPVER, _IFACES,
        _IN_IFACE/_OUT_IFACE (iptables, nftables, FortiGate), _ESTABLISHED, _HITS, _SEQ
"""

import re
from collections import OrderedDict

from pyfrc2g.model.netmodel import ip_version_label, ip_versions
from pyfrc2g.utils import get_dest_val, get_port_val, get_source_val, map_value, normalize_interface

FLOATING_GROUP = "Floating-rules"
ACTIONS = ("pass", "block", "reject")


# ---------------------------------------------------------------------------
# Shared row helpers
# ---------------------------------------------------------------------------

def is_true(value):
    """CSV boolean ("True" / "1")."""
    return str(value or "").strip() in ("True", "1")


def interface_part(gateway):
    """'fw/LAN' -> 'LAN'."""
    gateway = gateway or ""
    return gateway.split("/", 1)[1] if "/" in gateway else gateway


def interface_names(gateway):
    """'fw/WAN, LAN' -> {'wan', 'lan'}."""
    return {part.strip().lower() for part in interface_part(gateway).split(",") if part.strip()}


def interface_of(row):
    """Display interface of a rule row ('Floating-rules' for floating rules)."""
    if is_true(row.get("FLOATING")):
        return FLOATING_GROUP
    return interface_part((row.get("GATEWAY") or "").strip())


def rule_summary(row, with_comment=False):
    """'pass LAN -> srv [inet tcp 443]' (+ comment)."""
    text = (f"{row.get('ACTION', '')} {row.get('SOURCE', '')} -> {row.get('DESTINATION', '')} "
            f"[{row.get('PROTOCOL', '')} {row.get('PORT', '')}]")
    if with_comment and row.get("COMMENT"):
        text += f" {row.get('COMMENT')}"
    return text.strip()


def interface_stats(rows):
    """{interface: {"total", "pass", "block", "reject", "disabled"}} in first-seen order."""
    stats = OrderedDict()
    for row in rows:
        s = stats.setdefault(interface_of(row), {"total": 0, "disabled": 0,
                                                  **dict.fromkeys(ACTIONS, 0)})
        s["total"] += 1
        action = (row.get("ACTION") or "").strip().lower()
        if action in s:
            s[action] += 1
        if is_true(row.get("DISABLED")):
            s["disabled"] += 1
    return stats


# ---------------------------------------------------------------------------
# Entries -> rows
# ---------------------------------------------------------------------------

def interface_set(value):
    """'lan,opt1' / ['lan', 'opt1'] -> {'lan', 'opt1'}."""
    return {part.strip().lower() for part in normalize_interface(value).split(",") if part.strip()}


def is_floating_entry(entry):
    """True if rule is floating (no interface or explicitly tagged). Same logic for API and backup."""
    return bool(entry.get("floating") or not entry.get("interface"))


def _gateway(entry, config):
    """GATEWAY cell: gateway_name/interfaces ('Floating-rules' for floating single-interface rules)."""
    interface = normalize_interface(entry.get("interface"))
    if interface and (not entry.get("floating") or "," in interface):
        return f"{config.gateway_name}/{map_value(interface, 'interface', config.any_value)}"
    return f"{config.gateway_name}/{FLOATING_GROUP}"


def _protocol(entry):
    """PROTOCOL cell from ipprotocol + protocol (e.g. 'inet tcp', 'inet6 Any')."""
    ipp = (entry.get("ipprotocol") or "").strip()
    prot = (entry.get("protocol") or "").strip() or "Any"
    return f"{ipp} {prot}" if ipp else prot


def _raw(value):
    """Raw field value as a string (lists joined with commas, None -> 'any')."""
    if value is None:
        return "any"
    if isinstance(value, (list, tuple)):
        return ",".join(str(v) for v in value)
    return str(value)


# OPNsense automatic rules (default deny, anti-lockout, DHCP, bogons...) are returned by the
# API with show_all=1, flagged "is_automatic": true (and identified by a 32-hex label, user
# rules having a UUID). They are generated by the firewall and never stored in config.xml.
_AUTOMATIC_ID = re.compile(r"^[0-9a-f]{32}$")


def is_automatic_entry(entry, gateway_type):
    """True for a rule generated by the firewall itself (not configured by the administrator)."""
    for key in ("automatic", "is_automatic"):
        if entry.get(key) is not None:
            return str(entry.get(key)).strip().lower() in ("true", "1", "yes")
    if gateway_type != "opnsense":
        return False
    return bool(_AUTOMATIC_ID.match(str(entry.get("uuid") or "").lower()))


_TRUE = ("1", "true", "yes", "on")


def _flag(value):
    return str(value).strip().lower() in _TRUE


def is_quick(entry, gateway_type):
    """
    pf "quick": a matching quick rule decides at once; a non-quick rule only gives the decision
    when no later rule matches (pf last match). pfSense interface rules are always quick; its
    floating rules only when ticked. OPNsense rules are quick unless "quick" is false
    (default deny, "let out anything from firewall host itself").
    """
    floating = is_floating_entry(entry)
    if gateway_type == "pfsense" and not floating:
        return True
    value = entry.get("quick")
    if value is None or value == "":
        return gateway_type != "pfsense"
    return value is True or _flag(value)


def direction_of(entry):
    """in / out / any (default in)."""
    value = str(entry.get("direction") or "in").strip().lower()
    return value if value in ("in", "out", "any") else "in"


def _negated(value, flag):
    if value and _flag(flag) and not str(value).startswith("!"):
        return f"!{value}"
    return value


def _interface_ids(value):
    """Interface ids of a rule ('LAN' description -> 'lan' id when known)."""
    from pyfrc2g.model.netmodel import interface_id

    return tuple(sorted({interface_id(i) or i for i in interface_set(value) if i != "floating"}))


def entry_to_row(entry, config, gateway, rule_order):
    """Convert one rule entry to a row (pfSense entries use type/descr/disabled, others action/description/enabled)."""
    if config.gateway_type == "pfsense":
        source, dest, port = entry.get("source"), entry.get("destination"), entry.get("destination_port")
        action, comment = entry.get("type"), entry.get("descr")
        disabled = bool(entry.get("disabled"))
    else:
        source, dest, port = get_source_val(entry), get_dest_val(entry), get_port_val(entry)
        source = _negated(source, entry.get("source_not"))  # OPNsense API rows.
        dest = _negated(dest, entry.get("destination_not"))
        action, comment = entry.get("action") or entry.get("type"), entry.get("description")
        if not action and config.gateway_type == "opnsense":
            action = "pass"  # OPNsense generated rules without action are pass rules (pf default).
        disabled = not entry.get("enabled", True)
    # An empty address or port (OPNsense API: "source_net": "", "destination_port": "") means any.
    source = source if source not in ("", []) else None
    dest = dest if dest not in ("", []) else None
    port = port if port not in ("", []) else None
    ip_default = "inet" if config.gateway_type in ("pfsense", "opnsense") else "inet46"
    versions = ip_versions(entry.get("ipprotocol"), default=ip_default)
    any_value = config.any_value
    return {
        "SOURCE": map_value(source, "source", any_value),
        "GATEWAY": gateway,
        "ACTION": map_value(action, None, any_value),
        "PROTOCOL": map_value(_protocol(entry), None, any_value),
        "PORT": map_value(port, "destination_port", any_value),
        "DESTINATION": map_value(dest, "destination", any_value),
        "COMMENT": str(comment or ""),
        "DISABLED": str(disabled),
        "FLOATING": str(is_floating_entry(entry)),
        "RULE ORDER": str(rule_order),
        # Stable identifier: tracker (pfSense; the API "id" is positional) or uuid / hash.
        "RULE ID": str(entry.get("tracker") or entry.get("uuid") or ""),
        "IP VERSION": ip_version_label(versions),
        "AUTOMATIC": str(is_automatic_entry(entry, config.gateway_type)),
        "DIRECTION": direction_of(entry),
        "_QUICK": is_quick(entry, config.gateway_type),
        "_DIRECTION": direction_of(entry),
        "_SRC": _raw(source),
        "_DST": _raw(dest),
        "_PORT": _raw(port),
        "_PROTO": str(entry.get("protocol") or "any"),
        "_IPVER": tuple(sorted(versions)),
        "_IFACES": _interface_ids(entry.get("interface")),
        "_IN_IFACE": str(entry.get("in_iface") or ""),
        "_OUT_IFACE": str(entry.get("out_iface") or ""),
        "_ESTABLISHED": bool(entry.get("established_only")),
        "_HITS": entry.get("_hits"),
    }


def build_rule_rows(entries, config):
    """Convert rule entries to rows, numbering rules per gateway/interface (RULE ORDER)."""
    rows = []
    counters = {}
    for seq, entry in enumerate(entries):
        gateway = _gateway(entry, config)
        counters[gateway] = counters.get(gateway, 0) + 1
        row = entry_to_row(entry, config, gateway, counters[gateway])
        row["_SEQ"] = seq
        rows.append(row)
    return rows


# ---------------------------------------------------------------------------
# Filters
# ---------------------------------------------------------------------------

def filter_by_interfaces(entries, interfaces, keep_floating=True):
    """Keep entries on one of the given interfaces (and floating rules if keep_floating)."""
    if not interfaces:
        return entries
    wanted = {i.lower() for i in interfaces}
    return [entry for entry in entries
            if (keep_floating and is_floating_entry(entry)) or interface_set(entry.get("interface")) & wanted]


def filter_by_ip_version(rows, version):
    """Keep rules that apply to IPv4 (version 4) or IPv6 (version 6)."""
    if not version:
        return rows
    return [row for row in rows if int(version) in (row.get("_IPVER") or (4, 6))]
