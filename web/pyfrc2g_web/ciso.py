"""
CISO Assistant integration: send the PDF report of an analysis as a new revision of an
evidence (same API as the engine: POST /api/evidence-revisions/).

Settings (encrypted in the database, Administration > CISO Assistant): URL, API token, folder
id (default; a firewall can have its own), default evidence id, TLS verification / internal CA, automatic upload after each new
analysis. A firewall can have its own evidence id (firewall page > Reports & files).
"""

import logging
import os
import tempfile

PDF_SUFFIX = "_FLOW_MATRIX.pdf"
CHANGES_SUFFIX = "_CHANGES.csv"
DEFAULT_OBSERVATION = "Firewall rules flow matrix of {gateway} generated by PyFRC2G on {date} (risk score {score})"
TIMEOUT = 60


def configured(settings):
    """True when the integration is enabled and every required setting is filled."""
    return bool(settings.get("ciso_enabled") and settings.get("ciso_url") and settings.get("ciso_token")
                and settings.get("ciso_folder_id"))


def evidence_for(settings, gateway):
    """Evidence id of a firewall: its own one, else the default one ('' if none)."""
    return ((gateway or {}).get("ciso_evidence_id") or settings.get("ciso_evidence_id") or "").strip()


def options_of(db, gateway):
    """Options (fwopts) of the source of a gateway: its API firewall, its file settings, or defaults."""
    from pyfrc2g_web import fwopts

    firewall = db.firewall(gateway["firewall_id"]) if gateway and gateway.get("firewall_id") else None
    if firewall:
        return fwopts.options(firewall)
    return fwopts.options({"config": (gateway or {}).get("options") or {}})


def folder_for(settings, gateway, site=""):
    """
    Folder (domain) id of a firewall: its own one, else the one of its site
    (Administration > CISO Assistant), else the default one.
    """
    own = ((gateway or {}).get("ciso_folder_id") or "").strip()
    by_site = (settings.get("ciso_site_folders") or {}).get(site or "", "")
    return own or by_site or (settings.get("ciso_folder_id") or "").strip()


def folder_origin(settings, gateway, site=""):
    """'own', 'site' or 'default': where the folder of a firewall comes from."""
    if ((gateway or {}).get("ciso_folder_id") or "").strip():
        return "own"
    return "site" if (settings.get("ciso_site_folders") or {}).get(site or "") else "default"


def changes_evidence_for(settings, opts):
    """Evidence of the change report ('' = not sent)."""
    if not settings.get("ciso_changes"):
        return ""
    return (opts.get("ciso_changes_evidence_id") or settings.get("ciso_changes_evidence_id") or "").strip()


def observation(settings, gateway_name, analysis):
    template = (settings.get("ciso_observation") or DEFAULT_OBSERVATION).strip()
    risk = (analysis.get("data") or {}).get("risk") or {}
    values = {"gateway": gateway_name, "date": analysis.get("created", ""),
              "score": risk.get("score") if risk.get("score") is not None else "-",
              "level": risk.get("level") or "-"}
    try:
        return template.format(**values)
    except (KeyError, IndexError, ValueError):
        return template


class _Verify:
    """requests 'verify' value; an internal CA is written to a temporary file for the request."""

    def __init__(self, settings, tmp_dir):
        self.settings = settings
        self.tmp_dir = tmp_dir
        self.path = None

    def __enter__(self):
        pem = (self.settings.get("ciso_ca_pem") or "").strip()
        if pem:
            os.makedirs(self.tmp_dir, mode=0o700, exist_ok=True)
            fd, self.path = tempfile.mkstemp(prefix="ciso-ca-", suffix=".pem", dir=self.tmp_dir)
            with os.fdopen(fd, "w") as f:
                f.write(pem)
            return self.path
        verify = bool(self.settings.get("ciso_verify_ssl", True))
        if not verify:
            import urllib3

            urllib3.disable_warnings(urllib3.exceptions.InsecureRequestWarning)
        return verify

    def __exit__(self, *exc):
        if self.path and os.path.exists(self.path):
            os.remove(self.path)
        return False


def _api(settings, path):
    return f"{settings['ciso_url'].rstrip('/')}/api/{path.lstrip('/')}"


def _headers(settings):
    return {"Authorization": f"Token {settings['ciso_token']}", "Accept": "application/json"}


def _explain(error):
    import requests

    if isinstance(error, requests.exceptions.HTTPError) and error.response is not None:
        status = error.response.status_code
        return {401: "authentication failed: check the API token",
                403: "access forbidden: check the permissions of the token",
                404: "not found: check the URL, folder id and evidence id"}.get(
            status, f"HTTP error {status}: {error.response.text[:200]}")
    if isinstance(error, requests.exceptions.SSLError):
        return "TLS certificate error: provide the internal CA or disable verification"
    if isinstance(error, requests.exceptions.ConnectionError):
        return "connection error: check the URL and that CISO Assistant is reachable"
    if isinstance(error, requests.exceptions.Timeout):
        return "timeout"
    return str(error)


def upload(settings, evidence_id, filename, content, note, tmp_dir, folder_id=None, content_type="application/pdf"):
    """Send a PDF as a new evidence revision. Returns (ok, message)."""
    import requests

    if not configured(settings):
        return False, "CISO Assistant is not configured (Administration > CISO Assistant)"
    if not evidence_id:
        return False, "no evidence id for this firewall (set one on the firewall page or a default one)"
    data = {"is_published": "true", "observation": note, "folder": folder_id or settings["ciso_folder_id"],
            "evidence": evidence_id}
    try:
        with _Verify(settings, tmp_dir) as verify:
            response = requests.post(_api(settings, "evidence-revisions/"), headers=_headers(settings),
                                     data=data, files={"attachment": (filename, content, content_type)},
                                     verify=verify, timeout=TIMEOUT)
            response.raise_for_status()
    except Exception as e:  # requests errors, OSError...
        message = _explain(e)
        logging.error(f"CISO Assistant upload of {filename} failed: {message}")
        return False, message
    revision = ""
    try:
        body = response.json()
        revision = body.get("id") or body.get("version") or ""
    except ValueError:
        pass
    message = f"{filename} sent to evidence {evidence_id}" + (f" (revision {revision})" if revision else "")
    logging.info(f"✓ CISO Assistant: {message}")
    return True, message


def test_connection(settings, tmp_dir):
    """Check the URL, token, folder and default evidence. Returns (ok, message)."""
    import requests

    if not configured(settings):
        return False, "fill in and enable the URL, API token and folder id first"
    checks = [("folder", f"folders/{settings['ciso_folder_id']}/")]
    if settings.get("ciso_evidence_id"):
        checks.append(("evidence", f"evidences/{settings['ciso_evidence_id']}/"))
    names = []
    try:
        with _Verify(settings, tmp_dir) as verify:
            for label, path in checks:
                response = requests.get(_api(settings, path), headers=_headers(settings), verify=verify,
                                        timeout=20)
                response.raise_for_status()
                try:
                    names.append(f"{label} “{response.json().get('name', '?')}”")
                except ValueError:
                    names.append(label)
    except Exception as e:
        return False, _explain(e)
    return True, "Connection OK: " + ", ".join(names)


def send_analysis(db, settings, analysis_id, tmp_dir, username="-"):
    """
    Upload the PDF report of a stored analysis (and its change report when enabled) and record
    the results. Returns (ok, message).
    """
    analysis = db.analysis(analysis_id)
    if analysis is None:
        return False, "analysis not found"
    gateway = next((g for g in db.gateways() if g["id"] == analysis["gateway_id"]), None)
    name = gateway["name"] if gateway else "?"
    opts = options_of(db, gateway)
    folder = folder_for(settings, gateway, opts["site"])
    pdf = db.artifact(analysis_id, f"{name}{PDF_SUFFIX}")
    evidence = evidence_for(settings, gateway)
    if pdf is None:
        ok, message = False, "no PDF report stored for this analysis"
    else:
        ok, message = upload(settings, evidence, f"{name}{PDF_SUFFIX}", pdf["content"],
                             observation(settings, name, analysis), tmp_dir, folder_id=folder)
    db.add_ciso_upload(analysis_id, name, evidence, ok, message, username)
    db.add_event(username, "CISO Assistant upload" if ok else "CISO Assistant upload failed",
                 f"{name}: {message}")

    changes_evidence = changes_evidence_for(settings, opts)
    changes = db.artifact(analysis_id, f"{name}{CHANGES_SUFFIX}") if changes_evidence else None
    if changes is not None:
        note = f"Change report of {name} generated by PyFRC2G on {analysis.get('created', '')}"
        changes_ok, changes_message = upload(settings, changes_evidence, f"{name}{CHANGES_SUFFIX}",
                                             changes["content"], note, tmp_dir, folder_id=folder,
                                             content_type="text/csv")
        changes_message = f"change report: {changes_message}"
        db.add_ciso_upload(analysis_id, name, changes_evidence, changes_ok, changes_message, username)
        db.add_event(username, "CISO Assistant upload" if changes_ok else "CISO Assistant upload failed",
                     f"{name}: {changes_message}")
        ok, message = ok and changes_ok, f"{message}; {changes_message}"
    return ok, message
